namespace Webkernel\Platform\Components\Concerns;

use Webkernel\Platform\Components\Enums\Size;

/**
 * Size prop shared by button, badge, link, and related atoms.
 *
 * @property array<string, mixed> $props
 */
trait HasSize
{
    /**
     * @param $size Size|string
     *
     * @return static
     */
    public function size(Size|string $size): static
    {
        $this->props['size'] = $size instanceof Size ? $size->value : $size;

        return $this;
    }
}
